// Explicit live smoke: uses only a disposable test account created by the release owner.
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const out = path.join(root, 'outputs/reconciliation');
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const results = [];
(async () => {
  const credentials = JSON.parse(fs.readFileSync(path.join(os.homedir(), '.config/stock-iteready/accounts/stock-reconcile-check.json')));
  assert.equal(credentials.username, 'stock-reconcile-check');
  const browser = await chromium.launch({headless:true, channel:'chrome'});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000}});
    const page = await context.newPage();
    const errors=[];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('https://stock.iteready.com/?date=2026-09-04&scope=all');
    await page.getByRole('button',{name:'登录',exact:true}).waitFor();
    assert.equal((await context.request.get('https://api.stock.iteready.com/data/manifest.json')).status(),401);
    results.push({name:'anonymous API rejected',passed:true});
    await page.getByLabel('账号',{exact:true}).fill(credentials.username);
    await page.getByLabel('密码',{exact:true}).fill(credentials.password);
    await page.getByRole('button',{name:'登录',exact:true}).click();
    await page.getByRole('button',{name:'查看待核验',exact:true}).waitFor({timeout:30000});
    assert.equal(await page.locator('.results tbody tr').count(),30);
    assert.equal(await page.locator('.results tbody').getByText('贵州茅台',{exact:true}).count(),0);
    results.push({name:'default ranking excludes unverified records',passed:true,visibleRows:30});
    const api = await context.request.get('https://api.stock.iteready.com/data/2026-09-04.json');
    assert.equal(api.status(),200);
    const raw=await api.body();
    assert.deepEqual(JSON.parse(raw),JSON.parse(fs.readFileSync(path.join(out,'production-candidate/2026-09-04.json'))));
    const data=JSON.parse(raw);
    const suspect=data.rows.find(r=>r.code==='600519');
    assert.equal(suspect.status,'unverified');assert.equal(suspect.ratio,null);assert.equal(suspect.dayVolumeDifference,-44600);
    results.push({name:'authenticated data matches candidate and retains real failed attempts',passed:true,sha256:sha(raw)});
    await page.getByRole('button',{name:'查看待核验',exact:true}).click();
    await page.getByRole('button',{name:'隐藏待核验',exact:true}).waitFor();
    assert.equal(await page.locator('.results tbody tr').count(),32);
    assert.equal(new URL(page.url()).searchParams.get('unverified'),'1');
    assert.equal(await page.locator('.results tbody').getByText('贵州茅台',{exact:true}).count(),1);
    results.push({name:'pending toggle restores records and is retained in share URL',passed:true});
    await page.screenshot({path:path.join(out,'all-stocks.png'),fullPage:true});
    await page.goto('https://stock.iteready.com/?date=2026-09-04&scope=single&symbols=600519');
    await page.locator('.results tbody tr').waitFor();
    assert.equal(await page.locator('.results tbody tr').count(),1);
    const row=page.locator('.results tbody tr');
    assert.match(await row.innerText(),/待核验/);
    assert.equal(await row.locator('.ratio-display').count(),0);
    await row.locator('summary').click();
    assert.match(await row.innerText(),/17\.08%/);
    assert.match(await row.innerText(),/44,600/);
    assert.match(await row.innerText(),/不参与排名/);
    results.push({name:'single stock retains pending state and reference details',passed:true});
    await page.screenshot({path:path.join(out,'single-stock.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,'single-stock-mobile.png'),fullPage:true});
    await page.goto('https://stock.iteready.com/?from=2026-09-01&to=2026-09-04&scope=multiple&symbols=000001,600519&unverified=1');
    await page.locator('.results tbody tr').first().waitFor();
    assert.equal(await page.locator('.results tbody tr').count(),8);
    assert.equal(await page.locator('.results tbody .ratio-display').count(),4);
    results.push({name:'multi-stock date range preserves 8 records with only 4 verified ratios',passed:true});
    await page.goto('https://stock.iteready.com/?date=2026-09-04&scope=single&symbols=600519&min=1&unverified=1');
    await page.getByRole('button',{name:'清除占比筛选，查看待核验',exact:true}).click();
    await page.locator('.results tbody tr').waitFor();
    assert.equal(await page.locator('.results tbody tr').count(),1);
    assert.equal(new URL(page.url()).searchParams.has('min'),false);
    results.push({name:'minimum-filter share link can reveal pending record without treating reference as a valid ratio',passed:true});
    assert.equal(errors.length,0);
    results.push({name:'browser has no uncaught page errors',passed:true});
    const logout=await context.request.post('https://api.stock.iteready.com/auth/logout',{headers:{Origin:'https://stock.iteready.com'},data:{}});
    assert.equal(logout.status(),200);
    assert.equal((await context.request.get('https://api.stock.iteready.com/data/manifest.json')).status(),401);
    results.push({name:'logout invalidates test session',passed:true});
    await context.close();
  } finally {
    await browser.close();
    fs.writeFileSync(path.join(out,'live-verification.json'),JSON.stringify(results,null,2));
  }
  console.log(JSON.stringify(results));
})().catch(e=>{console.error(e.message);process.exitCode=1});
